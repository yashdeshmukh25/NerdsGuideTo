// One-off generator: turns a string set in Great Vibes into per-letter SVG
// path data (real glyph outlines, left-to-right) so a page can animate it as
// a handwriting-style, letter-by-letter ink reveal.
//
// Usage: node scripts/generate-title-path.js ["Some Text" [output/path.js]]
// Defaults to regenerating the homepage title at lib/titlePath.js.
// Requires opentype.js (devDependency) and the font file in
// scripts/assets/GreatVibes-Regular.ttf.
//
// Note: glyphs are placed manually (char -> glyph -> advance) instead of via
// font.getPath()/stringToGlyphs(), because this font's GSUB contextual-
// substitution table uses a lookup format opentype.js can't parse yet.

const fs = require("fs");
const path = require("path");
const opentype = require("opentype.js");

const TEXT = process.argv[2] || "Nerd's Guide To";
const OUT_ARG = process.argv[3] || "lib/titlePath.js";
const FONT_SIZE = 300;
const PADDING = 12;

const fontPath = path.join(__dirname, "assets/GreatVibes-Regular.ttf");
const buffer = fs.readFileSync(fontPath);
const font = opentype.parse(
  buffer.buffer.slice(buffer.byteOffset, buffer.byteOffset + buffer.byteLength)
);

const scale = FONT_SIZE / font.unitsPerEm;

// opentype.js's own Path.toPathData() tries to emit "smooth curve" shorthand
// by reflecting control points across adjacent commands, which breaks (NaN)
// once you concatenate many independent glyph subpaths together. Serialize
// manually instead: absolute M/L/C/Q/Z only, no cross-command reflection.
function serialize(commands, decimals) {
  const round = (n) => {
    const r = Number(n.toFixed(decimals));
    return Object.is(r, -0) ? 0 : r;
  };
  let d = "";
  for (const c of commands) {
    switch (c.type) {
      case "M":
        d += `M${round(c.x)} ${round(c.y)} `;
        break;
      case "L":
        d += `L${round(c.x)} ${round(c.y)} `;
        break;
      case "C":
        d += `C${round(c.x1)} ${round(c.y1)} ${round(c.x2)} ${round(c.y2)} ${round(c.x)} ${round(c.y)} `;
        break;
      case "Q":
        d += `Q${round(c.x1)} ${round(c.y1)} ${round(c.x)} ${round(c.y)} `;
        break;
      case "Z":
        d += "Z ";
        break;
      default:
        throw new Error(`Unhandled path command type: ${c.type}`);
    }
  }
  return d.trim();
}

// First pass: lay out every glyph at its advance-width position so we can
// measure the overall bounding box (used for the shared viewBox + origin).
let x = 0;
const glyphs = [];
for (const ch of TEXT) {
  const glyph = font.charToGlyph(ch);
  const glyphPath = glyph.getPath(x, 0, FONT_SIZE);
  glyphs.push({ ch, path: glyphPath, x });
  x += glyph.advanceWidth * scale;
}

const measurePath = new opentype.Path();
measurePath.commands = glyphs.flatMap((g) => g.path.commands);
const bbox = measurePath.getBoundingBox();

const minX = bbox.x1 - PADDING;
const minY = bbox.y1 - PADDING;
const width = bbox.x2 - bbox.x1 + PADDING * 2;
const height = bbox.y2 - bbox.y1 + PADDING * 2;

// Second pass: rebuild each glyph shifted into the final viewBox space, and
// record its own ink bounding box (not its advance box) so the letter-by-
// letter reveal can clip on real ink extent — connected-script glyphs like
// this font's often have tails/loops that spill past their advance width.
const letters = glyphs.map(({ ch, x: gx }) => {
  const glyph = font.charToGlyph(ch);
  const shiftedPath = glyph.getPath(gx - minX, -minY, FONT_SIZE);
  const d = serialize(shiftedPath.commands, 2);
  if (d.includes("NaN")) {
    throw new Error(`Generated path data for "${ch}" contains NaN.`);
  }
  if (!d) {
    // Whitespace and similar glyphs have no ink — skip them entirely.
    return null;
  }
  const gBox = shiftedPath.getBoundingBox();
  const round2 = (n) => Number(n.toFixed(2));
  return { d, x0: round2(gBox.x1), x1: round2(gBox.x2) };
}).filter(Boolean);

const out = `// AUTO-GENERATED by scripts/generate-title-path.js — do not hand-edit.
// Regenerate with: node scripts/generate-title-path.js "${TEXT}" ${OUT_ARG}
export const titlePath = {
  text: ${JSON.stringify(TEXT)},
  viewBox: "0 0 ${width.toFixed(2)} ${height.toFixed(2)}",
  letters: ${JSON.stringify(letters)},
};
`;

const outPath = path.join(__dirname, "..", OUT_ARG);
fs.mkdirSync(path.dirname(outPath), { recursive: true });
fs.writeFileSync(outPath, out);
console.log(`Wrote ${outPath}`);
console.log(`viewBox: 0 0 ${width.toFixed(2)} ${height.toFixed(2)} (${letters.length} letters)`);
